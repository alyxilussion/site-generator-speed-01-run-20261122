// solve.js — a faster drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// Reimplements makefun-site 1.0.0's build (the kit's vendor/makefun-site, make.fun's own
// reference program) as a single dependency-free ES module: run(input) returns the same
// output tree for every input, byte for byte, in less CPU time. The vendor code is the
// spec wherever it differs from its README; every rule below is ported from that code.
//
// Where the speed comes from (same answers, less work):
// - Markdown renders in one pass (no token objects) and escapes HTML in bulk runs instead
//   of one regex call per character.
// - Front matter is found by scanning line starts (the body is sliced, never split+joined).
// - slugify caches by input and skips NFKD + mark-stripping for pure-ASCII text (identity).
// - Templates parse once per case (as the reference does) and render recursively;
//   loop scopes are mutated per iteration, not rebuilt.
// - The per-page scope spread is replaced by a shared root scope (site/tags/recent).
// - Inline runs find their next special character with one regex search instead of a
//   per-character loop, and words are counted against a whitespace table.
// - Link targets resolve with manual scans, not per-link regexes; \r normalisation is
//   skipped when a file holds no \r at all.

